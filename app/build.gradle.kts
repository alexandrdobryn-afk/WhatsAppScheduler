val keystoreProperties = Properties().apply {
    val propertiesFile = rootProject.file("keystore.properties")
    if (propertiesFile.exists()) {
        propertiesFile.inputStream().use(::load)
    }
}

fun releaseSigningProperty(name: String): String? =
    providers.environmentVariable(name).orNull ?: keystoreProperties.getProperty(name)

val releaseStoreFile = releaseSigningProperty("WASCHEDULER_STORE_FILE")
val releaseStorePassword = releaseSigningProperty("WASCHEDULER_STORE_PASSWORD")
val releaseKeyAlias = releaseSigningProperty("WASCHEDULER_KEY_ALIAS")
val releaseKeyPassword = releaseSigningProperty("WASCHEDULER_KEY_PASSWORD")
val releaseSigningConfigured =
    !releaseStoreFile.isNullOrBlank() &&
        !releaseStorePassword.isNullOrBlank() &&
        !releaseKeyAlias.isNullOrBlank() &&
        !releaseKeyPassword.isNullOrBlank()

